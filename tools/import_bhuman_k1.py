#!/usr/bin/env python3
"""Convert B-Human's K1.rsi3 to the server's MJCF / sensor naming scheme.

Usage: python tools/import_bhuman_k1.py ../BHumanCodeRelease
Only robot assets change; field physics and client control parameters do not.
"""

import argparse
import copy
import hashlib
import itertools
import math
from pathlib import Path
import re
import shutil
import struct
import subprocess
import xml.etree.ElementTree as ET


JOINTS = {
    'HeadYaw': ('AAHead_yaw', 'Head_1'),
    'HeadPitch': ('Head_pitch', 'Head_2'),
    'LShoulderPitch': ('ALeft_Shoulder_Pitch', 'Left_Arm_1'),
    'LShoulderRoll': ('Left_Shoulder_Roll', 'Left_Arm_2'),
    'LElbowPitch': ('Left_Elbow_Pitch', 'Left_Arm_3'),
    'LElbowYaw': ('Left_Elbow_Yaw', 'left_hand_link'),
    'RShoulderPitch': ('ARight_Shoulder_Pitch', 'Right_Arm_1'),
    'RShoulderRoll': ('Right_Shoulder_Roll', 'Right_Arm_2'),
    'RElbowPitch': ('Right_Elbow_Pitch', 'Right_Arm_3'),
    'RElbowYaw': ('Right_Elbow_Yaw', 'right_hand_link'),
    'LHipPitch': ('Left_Hip_Pitch', 'Left_Hip_Pitch'),
    'LHipRoll': ('Left_Hip_Roll', 'Left_Hip_Roll'),
    'LHipYaw': ('Left_Hip_Yaw', 'Left_Hip_Yaw'),
    'LKneePitch': ('Left_Knee_Pitch', 'Left_Shank'),
    'LAnklePitch': ('Left_Ankle_Pitch', 'Left_Ankle_Cross'),
    'LAnkleRoll': ('Left_Ankle_Roll', 'left_foot_link'),
    'RHipPitch': ('Right_Hip_Pitch', 'Right_Hip_Pitch'),
    'RHipRoll': ('Right_Hip_Roll', 'Right_Hip_Roll'),
    'RHipYaw': ('Right_Hip_Yaw', 'Right_Hip_Yaw'),
    'RKneePitch': ('Right_Knee_Pitch', 'Right_Shank'),
    'RAnklePitch': ('Right_Ankle_Pitch', 'Right_Ankle_Cross'),
    'RAnkleRoll': ('Right_Ankle_Roll', 'right_foot_link'),
}


def number(value):
    match = re.fullmatch(r'([-+\d.eE]+)(.*)', value)
    if match is None:
        raise ValueError(value)
    scale = {'': 1, 'm': 1, 'mm': .001, 'g': .001, 'g*mm^2': 1e-9, 'degree': math.pi / 180}
    return float(match[1]) * scale[match[2]]


def values(sequence):
    return ' '.join(format(value, '.12g') for value in sequence)


def xyz(element):
    return [number(element.get(axis, '0')) for axis in 'xyz'] if element is not None else [0, 0, 0]


def pose(source):
    result = {'pos': values(xyz(source.find('Translation')))}
    rotation = source.find('Rotation')
    if rotation is not None:
        result['euler'] = values(xyz(rotation))
    return result


def convert(repository, destination, robot='K1', joints=None):
    joints = JOINTS if joints is None else joints
    source_dir = repository / ('Config/Scenes/Includes/' + robot)
    source = ET.parse(source_dir / (robot + '.rsi3')).getroot()
    destination.mkdir(exist_ok=True)
    original_path = destination.parent / robot / 'robot.xml'
    original = ET.fromstring(subprocess.check_output(['git', 'show', 'HEAD:src/rcsssmj/resources/robots/' + robot + '/robot.xml'], cwd=destination.parents[4]))
    result = ET.Element('mujoco', model=robot + 'BHuman')
    source_hash = hashlib.sha256((source_dir / (robot + '.rsi3')).read_bytes()).hexdigest()
    result.append(ET.Comment(' Generated by tools/import_bhuman_' + robot.lower() + '.py from B-Human Config/Scenes/Includes/' + robot + '/' + robot + '.rsi3; SHA256 ' + source_hash + '. See LICENSE.BHuman. '))
    ET.SubElement(result, 'compiler', angle='radian', meshdir='meshes_simrobot', inertiafromgeom='false')
    defaults = ET.SubElement(result, 'default')
    # ServoMotor::act() in the matching SimRobotCore3 sets these values.
    ET.SubElement(defaults, 'joint', armature='0.01', damping='0', frictionloss='0')
    ET.SubElement(defaults, 'geom', density='0')
    visual = ET.SubElement(defaults, 'default', {'class': 'visual'})
    ET.SubElement(visual, 'geom', type='mesh', contype='0', conaffinity='0', group='2')
    collision = ET.SubElement(defaults, 'default', {'class': 'collision'})
    # SimRobot mjs_addGeom defaults, including contact softness and friction.
    ET.SubElement(collision, 'geom', group='3', rgba='0.75 0.75 0.75 0', condim='3', friction='1 0 0')
    asset = ET.SubElement(result, 'asset')
    ET.SubElement(asset, 'material', name='team', rgba='0.4 0.4 0.4 1')
    ET.SubElement(asset, 'material', name='gray', rgba='0.2 0.2 0.2 1')
    mesh_dir = destination / 'meshes_simrobot'
    mesh_dir.mkdir(exist_ok=True)
    scene_path = repository / ('Config/Scenes/K1/GameFast3v3M.ros3' if robot == 'K1' else 'Config/Scenes/T1/GameFast.ros3')
    scene = ET.parse(scene_path).getroot()
    spawn = scene.find("Scene/Compound[@name='robots']/Body[@ref='" + robot + "']/Translation")
    spawn_height = number(spawn.get('z'))
    inputs = [source_dir / (robot + '.rsi3'), scene_path]
    for include in source.findall('Include'):
        path = source_dir / include.get('href')
        inputs.append(path)
        mesh_source = ET.parse(path).getroot()
        for appearance in mesh_source.findall('ComplexAppearance'):
            name = appearance.get('name')
            vertex_element = appearance.find('Vertices')
            if vertex_element.get('ref'):
                vertex_element = mesh_source.find("Vertices[@name='" + vertex_element.get('ref') + "']")
            vertices = list(map(float, vertex_element.text.split()))
            if vertex_element.get('unit') != 'm':
                raise ValueError('Unsupported vertex unit')
            # Triangles interleave vertex / normal indices.
            faces = list(map(int, appearance.findtext('Triangles').split()))[::2]
            with (mesh_dir / (name + '.stl')).open('wb') as output:
                output.write(('B-Human SimRobot ' + robot + ' visual mesh').encode().ljust(80, b'\0'))
                output.write(struct.pack('<I', len(faces) // 3))
                for offset in range(0, len(faces), 3):
                    triangle = [coordinate for index in faces[offset:offset + 3] for coordinate in vertices[3 * index:3 * index + 3]]
                    output.write(struct.pack('<12fH', 0, 0, 0, *triangle, 0))
            ET.SubElement(asset, 'mesh', name=name, file=name + '.stl')

    hinges = {element.get('name'): element for element in source.findall('Hinge')}
    original_bodies = {element.get('name'): element for element in original.iter('body')}
    collision_bodies = set()

    def body(source_body, parent, name, transform, hinge=None):
        target = ET.SubElement(parent, 'body', name=name, **transform)
        if hinge is None:
            ET.SubElement(target, 'freejoint', name='root')
        else:
            joint_name = joints[hinge.get('name')][0]
            axis = hinge.find('Axis')
            limit = axis.find('Deflection')
            motor = axis.find('ServoMotor')
            initial = number(limit.get('init', '0'))
            # Hinge::createPhysics rotates the body by init AND sets joint ref.
            if initial:
                direction = xyz(axis)
                target.set('quat', values([math.cos(initial / 2), *[a * math.sin(initial / 2) for a in direction]]))
            ET.SubElement(target, 'joint', name=joint_name, axis=values(xyz(axis)), range=values([number(limit.get('min')), number(limit.get('max'))]),
                          limited='true', ref=str(initial), armature=str(number(motor.get('armature', '0.01'))), actuatorfrcrange=values([-number(motor.get('maxForce')), number(motor.get('maxForce'))]))
        mass = source_body.find('InertiaMatrixMass')
        ET.SubElement(target, 'inertial', mass=str(number(mass.get('value'))), pos=values(xyz(mass)),
                      fullinertia=values([number(mass.get(key)) for key in ('ixx', 'iyy', 'izz', 'ixy', 'ixz', 'iyz')]))
        for site in original_bodies[name].findall('site'):
            site = copy.deepcopy(site)
            # Match CameraColor in K1.rsi3; retain protocol marker names.
            if site.get('name') == 'camera':
                camera = source_body.find('Camera')
                site.set('pos', values(xyz(camera.find('Translation'))))
                # Model-specific horizontal/vertical half-FOV in degrees.
                site.set('user', values([number(camera.get(key)) * 90 / math.pi for key in ('angleX', 'angleY')]))
            if robot == 'T1' and name == 'torso' and site.get('name') != 'torso':
                # Original server trunk frame is 62.5mm behind SimRobot's.
                position = [float(v) for v in site.get('pos', '0 0 0').split()]
                position[0] -= .0625
                site.set('pos', values(position))
            target.append(site)
        if robot == 'T1' and hinge is None:
            ET.SubElement(target, 'site', name='imu', pos=values(xyz(source_body.find('Gyroscope/Translation'))))
        for element in source_body:
            if element.tag == 'ComplexAppearance':
                ET.SubElement(target, 'geom', {'class': 'visual', 'mesh': element.get('ref'), 'material': 'team' if element.get('ref') == ('B_Trunk_Upper' if robot == 'K1' else 'B_Trunk') else 'gray', **pose(element)})
            elif element.tag.endswith('Geometry') and element.tag != 'Geometry':
                kind = element.tag.removesuffix('Geometry').lower()
                if kind == 'box':
                    size = [number(element.get(dim)) / 2 for dim in ('depth', 'width', 'height')]
                elif kind in ('capsule', 'cylinder'):
                    radius = number(element.get('radius'))
                    size = [radius, number(element.get('height')) / 2 - (radius if kind == 'capsule' else 0)]
                elif kind == 'sphere':
                    size = [number(element.get('radius'))]
                else:
                    raise ValueError('Unsupported geometry ' + kind)
                if name == 'torso' and kind == 'box':
                    geom_name = 'torso'
                elif robot == 'T1' and name in {'AL3', 'AR3'}:
                    # The referee recognizes forearm names for hand fouls.
                    geom_name = 'left_forearm' if name == 'AL3' else 'right_forearm'
                else:
                    geom_name = name + '_collision_' + str(len(target))
                ET.SubElement(target, 'geom', {'class': 'collision', 'name': geom_name, 'type': kind, 'size': values(size), **pose(element)})
                collision_bodies.add(name)
            elif element.tag == 'Hinge':
                child_hinge = hinges[element.get('ref')]
                body(child_hinge.find('Body'), target, joints[element.get('ref')][1], pose(element), child_hinge)
        return target

    world = ET.SubElement(result, 'worldbody')
    body(source.find("Body[@name='" + robot + "']"), world, 'torso', {'pos': values([0, 0, spawn_height])})
    # SimRobot uses a collision group per robot, excluding all self contacts.
    # Body exclusions preserve inter-robot contacts after server prefix/attach.
    contacts = ET.SubElement(result, 'contact')
    for first, second in itertools.combinations(sorted(collision_bodies), 2):
        ET.SubElement(contacts, 'exclude', body1=first, body2=second)
    # Preserve every actuator and sensor name expected by both existing teams.
    result.append(copy.deepcopy(original.find('actuator')))
    result.append(copy.deepcopy(original.find('sensor')))
    if robot == 'T1':
        for sensor in result.find('sensor'):
            if sensor.tag in ('gyro', 'accelerometer'):
                sensor.set('site', 'imu')
    custom = ET.SubElement(result, 'custom')
    ET.SubElement(custom, 'text', name=robot.lower() + '_model_source', data='BHuman-SimRobot')
    delay_value = source.find("Body[@name='" + robot + "']/Set[@name='Delay']")
    source_delay = number(delay_value.get('value')) if delay_value is not None else 0.
    for name, hinge in hinges.items():
        motor = hinge.find('Axis/ServoMotor')
        ET.SubElement(custom, 'numeric', name='simrobot_pd_' + joints[name][0], data=values([number(motor.get(key)) for key in ('p', 'd', 'maxForce')]))
        joint_name = joints[name][0]
        actuator_name = next(element.get('name').removesuffix('_tau') for element in original.find('actuator')
                             if element.tag == 'motor' and element.get('joint') == joint_name)
        # ServoMotor::create fixes the actuator ctrlrange from the XML.
        # setMotorParameters changes the software cap, not this hardware cap.
        for actuator in result.find('actuator'):
            if actuator.get('name') == actuator_name + '_tau':
                limit = number(motor.get('maxForce'))
                actuator.set('ctrllimited', 'true')
                actuator.set('ctrlrange', values([-limit, limit]))
        delay = motor.get('delay', '0')
        delay = source_delay if delay == '$Delay' else number(delay)
        if delay:
            ET.SubElement(custom, 'numeric', name='simrobot_delay_' + actuator_name, data=values([delay]))
        reference_step = number(scene.find('Scene').get('stepLength'))
        ET.SubElement(custom, 'numeric', name='simrobot_servo_' + actuator_name,
                      data=values([number(motor.get('velocityLowPassFactor', '1')), reference_step,
                                   *[number(motor.get(key)) for key in ('p', 'd', 'maxForce')]]))
    ET.indent(result, '  ')
    ET.ElementTree(result).write(destination / 'robot.xml', encoding='unicode')
    shutil.copyfile(repository / 'License.md', destination / 'LICENSE.BHuman')
    shutil.copyfile(original_path.parent / 'LICENSE', destination / 'LICENSE')
    (destination / 'SIMROBOT_SOURCE.sha256').write_text(''.join(hashlib.sha256(path.read_bytes()).hexdigest() + '  ' + str(path.relative_to(repository)) + '\n' for path in inputs))
    print('Generated ' + robot + 'BHuman/robot.xml; original ' + robot + ' model unchanged')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('bhuman_repo', type=Path)
    arguments = parser.parse_args()
    convert(arguments.bhuman_repo.resolve(), Path(__file__).resolve().parents[1] / 'src/rcsssmj/resources/robots/K1BHuman')
